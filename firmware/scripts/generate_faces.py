"""Generate deterministic hardware/Web/PC catalogs from one expression design source."""
import argparse,json,pathlib,sys
ROOT=pathlib.Path(__file__).resolve().parents[2]
FIELDS=['left_height','right_height','gaze_x','gaze_y','mouth_curve','mouth_open','left_width','right_width','brow_left','brow_right','brow_raise','brow_opa']

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    catalog=json.loads((ROOT/'shared/expressions.json').read_text(encoding='utf-8'))
    rows=catalog['expressions'];ids=[r['command'] for r in rows]
    assert len(rows)>10 and len(ids)==len(set(ids)) and ids[:2]==['idle','blink']
    enum=lambda text:text[0].upper()+text[1:]
    cpp=['// Generated by scripts/generate_faces.py; edit shared/expressions.json.','#pragma once','#include "face_model.h"','namespace nomi {',
         'enum class EyeKind { Normal, Smile, Heart };','enum class Decoration { None, Tears, Dots, Ring, Anger, Exclaim, Sleep, Question };',
         'struct FaceDesign { View view; const char *command; const char *label; Pose pose; EyeKind eyes; Decoration decor; bool zigzag; };',
         'inline constexpr FaceDesign face_designs[] = {']
    for r in rows:
        pose=', '.join(str(r['pose'][k]) for k in FIELDS)
        cpp.append('    {View::%s, "%s", "%s", {%s}, EyeKind::%s, Decoration::%s, %s},'%(enum(r['command']),r['command'],r['label'],pose,enum(r['eyes']),enum(r['decor']),'true' if r['mouth']=='zigzag' else 'false'))
    cpp+=['};','inline const FaceDesign &face_design(View view) {','    for (const auto &d:face_designs) if (d.view==view) return d;','    return face_designs[0];','}','}']
    voices={phrase:r['command'] for r in rows if r['command']!='idle' for phrase in r['voices']}
    py='# Generated by firmware/scripts/generate_faces.py; do not edit.\nFACE_COMMANDS = '+repr(tuple(ids))+'\nVOICE_FACES = '+repr(voices)+'\n'
    ts='// Generated by firmware/scripts/generate_faces.py; edit shared/expressions.json.\nexport const hardwareExpressions = '+json.dumps(rows,ensure_ascii=False,indent=2)+' as const;\nexport type HardwareExpression = (typeof hardwareExpressions)[number];\n'
    files={'firmware/main/face_catalog.h':'\n'.join(cpp)+'\n','tools/usb_asr/face_catalog.py':py,'frontend/src/features/hardware/expressions.generated.ts':ts}
    bad=[]
    for name,data in files.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=data:bad.append(name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data,encoding='utf-8')
    if bad:raise SystemExit('Stale generated catalogs: '+', '.join(bad))
    print(f'{len(rows)} expression designs synchronized across ESP32, PC and Web')
if __name__=='__main__':main()
